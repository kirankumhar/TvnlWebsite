    document.addEventListener('DOMContentLoaded', function() {
        /* ----------------------------
           📰 Flash News Pause/Play
        -----------------------------*/
        const toggleBtn = document.getElementById("toggleBtn");
        const track = document.getElementById("noticeTrack");
        if (toggleBtn && track) {
            toggleBtn.addEventListener("click", () => {
                const isPaused = track.style.animationPlayState === "paused";
                track.style.animationPlayState = isPaused ? "running" : "paused";
                toggleBtn.textContent = isPaused ? "⏸" : "▶️";
                toggleBtn.setAttribute("aria-pressed", String(!isPaused));
            });
        }

        /* ----------------------------
           🔠 Accessible Font Resize
        -----------------------------*/
        const elements = document.querySelectorAll(
            'p, h1, h2, h3, h4, h5, h6, li, a, span, label, button'
        );

        const STEP = 1; // px per click
        const MAX_CHANGE = 2; // ±2 px limit

        // 🧠 Ensure computed style reads AFTER CSS has applied
        window.requestAnimationFrame(() => {
            elements.forEach(el => {
                const style = window.getComputedStyle(el);
                const size = parseFloat(style.fontSize);
                el.dataset.origSize = size;
                el.dataset.currentSize = size;
            });
        });

        // Helper for applying new size
        const adjustFont = (delta) => {
            elements.forEach(el => {
                const orig = parseFloat(el.dataset.origSize);
                let current = parseFloat(el.dataset.currentSize);
                const newSize = current + delta;
                if (newSize <= orig + MAX_CHANGE && newSize >= orig - MAX_CHANGE) {
                    el.style.fontSize = newSize + 'px';
                    el.dataset.currentSize = newSize;
                }
            });
        };

        const incBtn = document.getElementById('increase-font');
        const decBtn = document.getElementById('decrease-font');
        const resetBtn = document.getElementById('reset-font');

        if (incBtn) incBtn.addEventListener('click', e => {
            e.preventDefault();
            adjustFont(STEP);
        });
        if (decBtn) decBtn.addEventListener('click', e => {
            e.preventDefault();
            adjustFont(-STEP);
        });
        if (resetBtn) resetBtn.addEventListener('click', e => {
            e.preventDefault();
            elements.forEach(el => {
                const orig = parseFloat(el.dataset.origSize);
                el.style.fontSize = orig + 'px';
                el.dataset.currentSize = orig;
            });
        });
    });
</script>



