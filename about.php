                    The first phase of the work was accomplished in 1995 with a total capital investment of
                    Rs.915 crores. This Thermal Power station was dedicated to the nation on 9th December, 1995
                    by the then Chief Minister of Bihar. But due to some technical snags the first phase came to
                    a stand still on February 5, 1996.</p>
